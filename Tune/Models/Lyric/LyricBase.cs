using DevBase.Format.Structure;
using DevBase.Generics;
using Tune.Values.Static;

namespace Tune.Models.Lyric
{
    /// <summary>
    /// Lyric Model
    /// Nullable: true
    /// </summary>
    public abstract class LyricBase
    {
        public abstract bool isTranslated { get; set; }
        public abstract AList<TimeStampedLyric> Lyrics { get; set; }
        public abstract AList<TimeStampedLyric> TranslatedLyrics { get; set; }
        public abstract List<TimeSpan> TranslatedTimestamps { get; set; }

        /// <summary>
        /// All lyric lines grouped by timestamp, each group keeping the order it had in the
        /// file. A group of three normally reads as original, translation, romanisation.
        /// </summary>
        public List<List<TimeStampedLyric>> LyricsByTimestamp { get; set; } = new List<List<TimeStampedLyric>>();

        /// <summary>
        /// Gets the isTranslated flag by checking if there are any timestamps with different texts in the raw parse result.
        /// **NOTE**: If the lyric is translated, do not directly use the raw parse result, call `DepartTranslatedLyrics` first to separate the translated lyrics.
        /// </summary>
        /// <param name="rawParseResult"></param>
        /// <returns></returns>
        public bool GetIsTranslatedAndFlag(AList<TimeStampedLyric> rawParseResult)
        {
            var filtered = rawParseResult
                .Where(l => !string.IsNullOrWhiteSpace(l.Text))
                .ToList();

            var grouped = filtered.GroupBy(l => l.StartTimestamp);
            bool result = grouped.Any(g => g.Select(x => x.Text).Distinct().Count() > 1);
            isTranslated = result;
            return result;
        }

        /// <summary>
        /// This method is Generated by Agent.
        /// 将解析得到的原始歌词结果分离出翻译部分。
        /// 逻辑：按时间戳分组，同一时间戳的第一条文本视为主歌词，其后的同时间戳条目视为翻译文本。
        /// 分离后会填充 Lyrics、TranslatedLyrics 和 TranslatedTimestamps 属性。
        /// </summary>
        /// <param name="rawParseResult">来自解析器的原始歌词列表</param>
        public void DepartTranslatedLyrics(AList<TimeStampedLyric> rawParseResult)
        {
            // 初始化容器
            TranslatedLyrics = new AList<TimeStampedLyric>();
            TranslatedTimestamps = new List<TimeSpan>();
            Lyrics = new AList<TimeStampedLyric>();

            if (rawParseResult == null)
            {
                return;
            }

            // Every line of a timestamp is kept in file order, which is what lets a group of
            // three be shown as original, translation and romanisation.
            LyricsByTimestamp = rawParseResult
                .Where(l => !string.IsNullOrWhiteSpace(l.Text))
                .GroupBy(l => l.StartTimestamp)
                .OrderBy(g => g.Key)
                .Select(g => g.ToList())
                .ToList();

            // 过滤空文本并按时间戳分组
            var grouped = rawParseResult
                .Where(l => !string.IsNullOrWhiteSpace(l.Text))
                .GroupBy(l => l.StartTimestamp)
                .OrderBy(g => g.Key);

            foreach (var g in grouped)
            {
                var items = g.ToList();
                if (items.Count == 0)
                    continue;

                // 第一条作为主歌词
                Lyrics.Add(items[0]);

                // 如果存在额外条目，视为翻译并记录时间戳
                if (items.Count > 1)
                {
                    for (int i = 1; i < items.Count; i++)
                    {
                        TranslatedLyrics.Add(items[i]);
                    }
                    // StartTimestamp 在解析器中为 long（毫秒），转换为 TimeSpan
                    TranslatedTimestamps.Add(TimeSpan.FromMilliseconds(g.Key));
                }
            }
        }

        /// <summary>Gets how many lyric entries the file has, one per timestamp.</summary>
        public int LyricCount => LyricsByTimestamp.Count;

        /// <summary>
        /// Gets the one-based position of the entry that belongs to a moment, or zero when the
        /// moment comes before the first entry.
        /// </summary>
        /// <param name="seconds">The moment to look up, in seconds.</param>
        public int GetLyricPositionAtTime(double seconds)
        {
            TimeSpan target = TimeSpan.FromSeconds(seconds);
            int position = 0;

            for (int i = 0; i < LyricsByTimestamp.Count; i++)
            {
                List<TimeStampedLyric> group = LyricsByTimestamp[i];
                if (group.Count == 0) continue;
                if (group[0].StartTime > target) break;

                position = i + 1;
            }

            return position;
        }

        /// <summary>
        /// Gets the lines that belong to a moment, in file order and at most
        /// <paramref name="limit"/> of them.
        /// </summary>
        /// <param name="seconds">The moment to look up, in seconds.</param>
        /// <param name="limit">How many lines may be shown; zero or less shows none.</param>
        public List<string> GetLyricLinesAtTime(double seconds, int limit)
        {
            var lines = new List<string>();

            if (limit <= 0 || LyricsByTimestamp.Count == 0)
                return lines;

            TimeSpan target = TimeSpan.FromSeconds(seconds);
            List<TimeStampedLyric>? current = null;

            foreach (List<TimeStampedLyric> group in LyricsByTimestamp)
            {
                if (group.Count == 0) continue;
                if (group[0].StartTime > target) break;

                current = group;
            }

            if (current == null)
                return lines;

            foreach (TimeStampedLyric line in current.Take(limit))
                lines.Add(line.Text);

            return lines;
        }

        /// <summary>
        /// 获取歌词
        /// </summary>
        /// <param name="seconds">当前秒</param>
        /// <param name="lyrics">歌词</param>
        /// <param name="holdLast">保持最后一句</param>
        /// <returns></returns>
        public string GetLyricAtTime(
            double seconds,
            AList<TimeStampedLyric>? lyrics,
            bool holdLast = true)
        {
            if (lyrics == null || lyrics.Length == 0)
                return Strings.NO_CONTENT;


            TimeSpan target = TimeSpan.FromSeconds(seconds);

            int left = 0;
            int right = lyrics.Length - 1;
            int resultIndex = -1;


            while (left <= right)
            {
                int mid = (left + right) / 2;

                if (lyrics[mid].StartTime <= target)
                {
                    resultIndex = mid;
                    left = mid + 1;
                }
                else
                {
                    right = mid - 1;
                }
            }


            if (resultIndex < 0)
                return Strings.NO_CONTENT;


            if (!holdLast && resultIndex == lyrics.Length - 1)
            {
                return Strings.NO_CONTENT;
            }


            return lyrics[resultIndex].Text;
        }

    }
}